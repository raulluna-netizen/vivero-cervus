        <h3>Plantas Acuáticas Flotantes (Superficie)</h3>
        <p>
            • Especies: Lenteja de agua, Limnobium, Jacinto de agua.
            • Luz: Alta y directa.
            • Función: Absorben nitratos a gran velocidad y controlan las algas dando sombra.
            • Cuidado clave: El agua no debe mojar la parte superior de sus hojas ni tener corriente fuerte, o se pudrirán.
        </p>
        <h3>Plantas Suspendidas o Sumergidas</h3>
        <p>      
            • Especies: Cola de zorro, Elodea, Naja.
            • Luz: Media a alta (debe atravesar el agua).
            • Función: Son las principales oxigenadoras del agua y ofrecen refugio subacuático.
            • Cuidado clave: No necesitan enterrarse en sustrato. Requieren podas constantes para que las partes bajas no mueran por falta de luz.
        </p>
        <h3>Cultivo de Berro de Agua</h3>
        <p>
            • Ubicación: Raíces sumergidas, pero tallos y hojas al aire libre (usa canastas flotantes).
            • Luz y Agua: Requiere luz brillante y prefiere aguas frescas (10°C a 22°C).
            • Función: Filtra el agua de forma masiva consumiendo nutrientes del fondo.
        </p>
        <h3>Cultivo de Pulgas de Agua </h3>
        <p>
            • Entorno: Contenedor separado sin peces. Usa solo un aireador muy lento (los filtros mecánicos las succionan).
            • Alimento: Levadura de cerveza disuelta en agua. Agrega unas gotas hasta que el agua enturbie levemente; no repitas el alimento hasta que el agua vuelva a estar 100% cristalina.
            • Mantenimiento: Cambios del 20% de agua semanal con agua sin cloro.
        </p>
        <h3>Caracoles Physa</h3>
        <p>
            • Alimento: Comen algas, hojas muertas y desechos. No dañan las plantas sanas.
            • Agua: Prefieren pH neutro o alcalino (7.0 a 8.0) para mantener sus conchas fuertes.
            • Población: Se reproducen según el alimento disponible. Si hay una explosión de caracoles, reduce la comida del tanque.
        </p>
